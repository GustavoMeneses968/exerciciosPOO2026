package reserva;
public class Quarto {
    private int numero;
    private boolean luxo;
    private boolean standart;

    public int getNumero() {
        return numero;
    }
    public void setNumero(int numero) {
        this.numero = numero;
    }
    public boolean isLuxo() {
        return luxo;
    }
    public void setLuxo(boolean luxo) {
        this.luxo = luxo;
    }
    public boolean isStandart() {
        return standart;
    }
    public void setStandart(boolean standart) {
        this.standart = standart;
    }


}
